-- Exports zone and exploration-criteria names/IDs from the AzerfolioDiag dump for the HTML mockups.
-- Usage: luajit tools/export-mock-data.lua > mockups/data.js
-- Only static game data is exported (no completion state, no character or chat data).
local path = os.getenv("AZF_DIAG_FILE")
    or "C:/Program Files (x86)/World of Warcraft/_forever_/WTF/Account/COMPUTERWISPERER/SavedVariables/AzerfolioDiag.lua"
local chunk = assert(loadfile(path))
local env = {}
setfenv(chunk, env)
chunk()
local DB = env.AzerfolioDiagDB

local maps = DB.maps.byID
local zones = {}
for achID, a in pairs(DB.achievements.explore) do
    local zoneName = a.name and a.name:match("^Explore (.+)$")
    local isZone = a.criteria[1] and a.criteria[1].type == 43
    if zoneName and isZone and a.matchedMapIDs and #a.matchedMapIDs == 1 then
        local mapID = a.matchedMapIDs[1]
        local m = maps[mapID]
        local parent = m and maps[m.parent]
        local criteria = {}
        for _, c in ipairs(a.criteria) do criteria[#criteria + 1] = { id = c.criteriaID, name = c.name } end
        table.sort(criteria, function(x, y) return x.name < y.name end)
        zones[#zones + 1] = {
            mapID = mapID, name = zoneName, achievementID = achID,
            continent = parent and parent.name or "?", criteria = criteria,
        }
    end
end
table.sort(zones, function(a, b) return a.name < b.name end)

local function q(s) return string.format("%q", s):gsub("\\\n", "\\n") end
local out = { "// Generated by tools/export-mock-data.lua from client data. Do not edit.", "window.AZF_ZONES = [" }
for _, z in ipairs(zones) do
    local cs = {}
    for _, c in ipairs(z.criteria) do cs[#cs + 1] = string.format("{id:%d,name:%s}", c.id, q(c.name)) end
    out[#out + 1] = string.format("  {mapID:%d,name:%s,achievementID:%d,continent:%s,criteria:[%s]},",
        z.mapID, q(z.name), z.achievementID, q(z.continent), table.concat(cs, ","))
end
out[#out + 1] = "];"
print(table.concat(out, "\n"))
