# Traces the painted road in each of the adventurer's road regions (mockups/DESIGN.md "Dungeons tab",
# round 6; art/prompts.md "The adventurer's road regions"): every panel has a pale dirt road crossing
# from the left edge to the right edge through the middle. This finds it so the drawn road, the gold
# progress and the medallions follow the painting.
#   mockups/dungeon-art/road<n>.png (1024x512, made by tools/process-art.ps1)
#     -> Azerfolio/Data/DungeonRoad.lua    (ns.DungeonRoad.lanes["road<n>"] = { y, ... }: the road's
#                                           middle as a fraction of the panel's height, at 65 evenly
#                                           spaced columns from the left edge to the right edge)
#     -> mockups/dungeon-art/road-lanes.js (the same for the mockup)
#     -> art/review/dungeon-road<n>-lane.png (the panel with the traced line, to check by eye)
# How: the road is a thin band lighter than the ground just above and below it, so a cell's score
# is its "ridge" (its brightness minus the mean of the cells a few rows above and below) less a
# little for saturation; the road is the best-scoring left-to-right path through the middle band
# that moves at most one cell up or down per column (dynamic programming), then smoothed. Run after process-art.ps1; never hand-edit the outputs.
param(
    [string]$ArtDir = (Join-Path $PSScriptRoot '..\mockups\dungeon-art'),
    [string]$OutLua = (Join-Path $PSScriptRoot '..\Azerfolio\Data\DungeonRoad.lua'),
    [string]$OutJs = (Join-Path $PSScriptRoot '..\mockups\dungeon-art\road-lanes.js'),
    [string]$ReviewDir = (Join-Path $PSScriptRoot '..\art\review'),
    [int]$Cell = 4, [int]$Reach = 4, # ridge: cells above and below compared            # cell size in pixels (the path moves one cell per column at most)
    [double]$BandTop = 0.35,   # the middle band searched, as fractions of the height
    [double]$BandBottom = 0.75,
    [int]$Samples = 65,
    [int]$Smooth = 3
)
Add-Type -AssemblyName System.Drawing
$ErrorActionPreference = 'Stop'
if (-not ('AzfRoadLane' -as [type]) -or -not [AzfRoadLane].GetMethod('Trace').GetParameters().Count -eq 5) {
    Add-Type -ReferencedAssemblies System.Drawing -TypeDefinition @'
using System;
using System.Collections.Generic;
using System.Drawing;
public static class AzfRoadLane {
    // Returns the road's middle row (pixels) for every cell column.
    public static double[] Trace(Bitmap bmp, int cell, double top, double bottom, int reach) {
        int cols = bmp.Width / cell, rows = bmp.Height / cell;
        int r0 = (int)(rows * top), r1 = (int)(rows * bottom);
        var col = new double[cols, rows, 3];
        var pale = new List<double[]>();
        for (int cx = 0; cx < cols; cx++) for (int cy = 0; cy < rows; cy++) {
            double r = 0, g = 0, b = 0; int n = 0;
            for (int y = cy * cell; y < (cy + 1) * cell; y++) for (int x = cx * cell; x < (cx + 1) * cell; x++) {
                Color c = bmp.GetPixel(x, y); r += c.R; g += c.G; b += c.B; n++; }
            r /= n; g /= n; b /= n; col[cx, cy, 0] = r; col[cx, cy, 1] = g; col[cx, cy, 2] = b;
            if (cy >= r0 && cy < r1) {
                double mx = Math.Max(r, Math.Max(g, b)), mn = Math.Min(r, Math.Min(g, b));
                pale.Add(new double[] { (r + g + b) / 3 - (mx - mn) * 1.5, r, g, b });
            }
        }
        int h = r1 - r0;
        Func<int, int, double> lum = (x, y) => (col[x, Math.Max(0, Math.Min(rows - 1, y)), 0] + col[x, Math.Max(0, Math.Min(rows - 1, y)), 1] + col[x, Math.Max(0, Math.Min(rows - 1, y)), 2]) / 3;
        var cost = new double[cols, h]; var from = new int[cols, h];
        for (int cx = 0; cx < cols; cx++) for (int i = 0; i < h; i++) {
            int cy = r0 + i;
            double sat = Math.Max(col[cx, cy, 0], Math.Max(col[cx, cy, 1], col[cx, cy, 2])) - Math.Min(col[cx, cy, 0], Math.Min(col[cx, cy, 1], col[cx, cy, 2]));
            double ridge = lum(cx, cy) - (lum(cx, cy - reach) + lum(cx, cy + reach)) / 2 - sat * 0.15;
            double d = 120 - ridge;
            if (cx == 0) { cost[cx, i] = d; continue; }
            double best = double.MaxValue; int bi = i;
            for (int k = -1; k <= 1; k++) { int j = i + k; if (j < 0 || j >= h) continue; double v = cost[cx - 1, j] + (k == 0 ? 0 : 4); if (v < best) { best = v; bi = j; } }
            cost[cx, i] = best + d; from[cx, i] = bi;
        }
        int end = 0; for (int i = 1; i < h; i++) if (cost[cols - 1, i] < cost[cols - 1, end]) end = i;
        var path = new double[cols];
        for (int cx = cols - 1; cx >= 0; cx--) { path[cx] = (r0 + end + 0.5) * cell; if (cx > 0) end = from[cx, end]; }
        return path;
    }
}
'@
}
New-Item -ItemType Directory -Force $ReviewDir | Out-Null
$inv = [Globalization.CultureInfo]::InvariantCulture
$lua = @('-- Generated by tools/trace-dungeon-road.ps1 from the painted road regions. Do not edit.',
    '-- lanes["road<n>"]: the painted road''s middle as a fraction of the panel height, at evenly spaced',
    '-- columns from the left edge (first) to the right edge (last).', 'local _, ns = ...', '', 'ns.DungeonRoad = {', '    lanes = {')
$js = @('// Generated by tools/trace-dungeon-road.ps1. Do not edit.', 'window.AZF_ROAD_LANES = {')
foreach ($f in Get-ChildItem $ArtDir -Filter 'road*.png' | Where-Object { $_.BaseName -match '^road\d+$' } | Sort-Object Name) {
    $bmp = [System.Drawing.Bitmap]::FromFile($f.FullName)
    $path = [AzfRoadLane]::Trace($bmp, $Cell, $BandTop, $BandBottom, $Reach)
    $n = $path.Count
    $sm = for ($i = 0; $i -lt $n; $i++) { $a = [Math]::Max(0, $i - $Smooth); $b = [Math]::Min($n - 1, $i + $Smooth); ($path[$a..$b] | Measure-Object -Average).Average }
    $ys = for ($s = 0; $s -lt $Samples; $s++) { $x = $s / ($Samples - 1) * ($n - 1); $i = [Math]::Floor($x); $j = [Math]::Min($n - 1, $i + 1); $t = $x - $i; (($sm[$i] * (1 - $t) + $sm[$j] * $t) / $bmp.Height) }
    $txt = ($ys | ForEach-Object { $_.ToString('0.000', $inv) }) -join ', '
    $lua += "        [""$($f.BaseName)""] = { $txt },"
    $js += "  $($f.BaseName): [$txt],"
    # Review image: the panel with the traced line.
    $rev = New-Object System.Drawing.Bitmap $bmp
    $g = [System.Drawing.Graphics]::FromImage($rev); $pen = New-Object System.Drawing.Pen ([System.Drawing.Color]::Magenta), 3
    $pts = for ($s = 0; $s -lt $Samples; $s++) { New-Object System.Drawing.PointF ([float]($s / ($Samples - 1) * ($bmp.Width - 1))), ([float]($ys[$s] * $bmp.Height)) }
    $g.DrawLines($pen, [System.Drawing.PointF[]]$pts); $g.Dispose(); $bmp.Dispose()
    $rev.Save((Join-Path (Resolve-Path $ReviewDir).Path "dungeon-$($f.BaseName)-lane.png")); $rev.Dispose()
    $min = ($ys | Measure-Object -Minimum).Minimum; $max = ($ys | Measure-Object -Maximum).Maximum
    Write-Output ("{0}: lane {1:0.000} to {2:0.000} of the height; left {3:0.000}, right {4:0.000}" -f $f.BaseName, $min, $max, $ys[0], $ys[$Samples - 1])
}
$lua += @('    },', '}')
$js += '};'
[IO.File]::WriteAllLines((Resolve-Path (Split-Path $OutLua)).Path + '\' + (Split-Path $OutLua -Leaf), $lua, (New-Object System.Text.UTF8Encoding $false))
[IO.File]::WriteAllLines((Resolve-Path (Split-Path $OutJs)).Path + '\' + (Split-Path $OutJs -Leaf), $js, (New-Object System.Text.UTF8Encoding $false))
