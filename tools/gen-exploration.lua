-- Generates Azerfolio/Data/Exploration.lua (the exploration catalogue) from the AzerfolioDiag dump.
-- Usage (from repo root): luajit tools/gen-exploration.lua [dump path]
-- Reproducible: the same dump gives the same file. Only static game IDs (and zone/area names as
-- comments) are written; no completion state, character, chat or friend data.
-- Source: each zone's "Explore <zone>" achievement; its criteria (type 43) are the zone's areas
-- and criteriaID is the objective ID (docs/research/exploration-validation.md). [verified-ingame]
local DEFAULT = "C:/Program Files (x86)/World of Warcraft/_forever_/WTF/Account/COMPUTERWISPERER/SavedVariables/AzerfolioDiag.lua"
local path = arg[1] or os.getenv("AZF_DIAG_FILE") or DEFAULT
local OUT = "Azerfolio/Data/Exploration.lua"
local DATA_VERSION = 1
local ZONE_CATEGORIES = { [14777] = true, [14778] = true } -- Eastern Kingdoms, Kalimdor
local AREA_TYPE = 43                                     -- criteria type "explore area"

local chunk = assert(loadfile(path))
local env = {}
setfenv(chunk, env)
chunk()
local DB = assert(env.AzerfolioDiagDB, "no AzerfolioDiagDB in " .. path)
local build = assert(DB.env and DB.env.build, "dump has no env.build")
local explore = assert(DB.achievements and DB.achievements.explore, "dump has no achievements.explore")

local problems = {}
local function problem(fmt, ...) problems[#problems + 1] = string.format(fmt, ...) end

local zones, seenCriteria, seenMaps = {}, {}, {}
for achID, a in pairs(explore) do
    local zoneName = type(a.name) == "string" and a.name:match("^Explore (.+)$")
    if zoneName and ZONE_CATEGORIES[a.category] then
        local maps = a.matchedMapIDs or {}
        if #maps ~= 1 then
            problem("%d %s: matches %d maps, expected 1", achID, a.name, #maps)
        else
            local mapID = maps[1]
            local list = {}
            for _, c in ipairs(a.criteria or {}) do list[#list + 1] = c end
            table.sort(list, function(x, y) return x.index < y.index end)
            if #list == 0 then problem("%d %s: no criteria", achID, a.name) end
            local criteria = {}
            for i, c in ipairs(list) do
                if c.index ~= i then problem("%d %s: criteria index gap at %d", achID, a.name, i) end
                if c.type ~= AREA_TYPE then problem("%d %s: criterion %d has type %s", achID, a.name, i, tostring(c.type)) end
                if type(c.criteriaID) ~= "number" then
                    problem("%d %s: criterion %d has no criteriaID", achID, a.name, i)
                else
                    if seenCriteria[c.criteriaID] then
                        problem("criteriaID %d in both %s and %s", c.criteriaID, seenCriteria[c.criteriaID], a.name)
                    end
                    seenCriteria[c.criteriaID] = a.name
                    criteria[#criteria + 1] = { id = c.criteriaID, name = c.name }
                end
            end
            if seenMaps[mapID] then problem("map %d has two achievements", mapID) end
            seenMaps[mapID] = true
            zones[#zones + 1] = { mapID = mapID, name = zoneName, achievementID = achID, criteria = criteria }
        end
    end
end
table.sort(zones, function(x, y) return x.mapID < y.mapID end)

if #problems > 0 then
    io.stderr:write("Catalogue not written:\n  " .. table.concat(problems, "\n  ") .. "\n")
    os.exit(1)
end

local function comment(s) return (tostring(s):gsub("[\r\n]", " ")) end
local out = {
    "-- Generated by tools/gen-exploration.lua from the AzerfolioDiag dump. Do not edit.",
    "-- Exploration catalogue: each zone's \"Explore <zone>\" achievement and its area criteria",
    "-- (criteriaID, in the game's order). Provenance: client-derived. Names and completion are",
    "-- read live from the client; names here are comments only.",
    "local _, ns = ...",
    "ns.ExplorationCatalogue = {",
    string.format("    dataVersion = %d,", DATA_VERSION),
    string.format("    clientVersion = %q,", tostring(build[1])),
    string.format("    clientBuild = %d,", tonumber(build[2])),
    "    zones = {",
}
local total = 0
for _, z in ipairs(zones) do
    out[#out + 1] = string.format("        [%d] = { achievementID = %d, criteria = { -- %s (%d)",
        z.mapID, z.achievementID, comment(z.name), #z.criteria)
    for _, c in ipairs(z.criteria) do
        out[#out + 1] = string.format("            %d, -- %s", c.id, comment(c.name))
    end
    out[#out + 1] = "        } },"
    total = total + #z.criteria
end
out[#out + 1] = "    },"
out[#out + 1] = "}"

local f = assert(io.open(OUT, "wb"))
f:write(table.concat(out, "\n"), "\n")
f:close()
print(string.format("Wrote %s: %d zones, %d criteria, client %s.%s", OUT, #zones, total,
    tostring(build[1]), tostring(build[2])))
